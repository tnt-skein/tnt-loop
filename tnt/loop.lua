--- Периодический цикл на фибере: такт, пауза, остановка.
---
--- Каждому наблюдателю нужен один и тот же цикл: делать такт, ждать до
--- следующего, просыпаться сразу при остановке и переживать падение такта.
--- Написанный заново в каждом пакете, он в каждом же и ошибается по-своему:
--- то период растёт вместе с временем такта, то остановка ждёт целый период,
--- то исключение молча убивает фибер и наблюдение прекращается навсегда.
---
--- Пауза считается от начала такта, а не от его конца: иначе период опроса
--- растёт вместе с временем ответа самого медленного узла, и частота
--- проверок начинает зависеть от состояния кластера — то есть падает
--- ровно тогда, когда наблюдение нужнее всего.
---
--- Такт исполняется под pcall: наблюдение обязано пережить собственную
--- ошибку. Мёртвый фибер не сообщает о себе ничем, и молчащий цикл выглядит
--- точно так же, как цикл, которому не о чем сообщить. По той же причине
--- под своим pcall зовётся и `on_error`: брошенное из обработчика убило
--- бы фибер так же, как брошенное из такта.
---
--- Настройки проверяются в `new`, на строке вызывающего (`tnt-must`).
--- Ошибка в них — ошибка программиста, а в фибере она не видна: цикл без
--- имени умирал бы первой строкой фибера, отвечая `running()` «да»,
--- такт, который не функция, каждый период отдавал бы `on_error`
--- «attempt to call a nil value», а обработчик с опечаткой в имени
--- (`on_eror`) молча оставлял бы падения без внимания.
---
--- Пауза меряется временем планировщика (`fiber.clock`), а не настоящими
--- часами, потому что уходит в ожидание: условная переменная отсчитывает
--- срок от отметки цикла событий, а та стоит на месте, пока такт работает
--- без уступки. Такт, проработавший так 90 мс, по настоящим часам получил
--- бы паузу на 90 мс короче, и отсчитана она была бы от застывшей отметки,
--- то есть кончилась бы ещё на 90 мс раньше: период вышел бы короче на всё
--- время работы, а такт дольше половины периода шёл бы вовсе без пауз.
--- По времени планировщика ожидание дожидается начала следующего периода.
---
--- Начало такта отмечается тем же временем планировщика, а не настоящими
--- часами, как велит правило `tnt-clock` для мига, — и это отступление.
--- Такт начинается сразу после ожидания, то есть на свежей отметке.
--- Отстаёт она в двух случаях: у первого такта — фибер цикла стартует
--- без оборота цикла событий, на отметке того, кто позвал `start`, —
--- и у такта, начатого без паузы вслед за тактом дольше периода. Период
--- такого такта выходит короче на это отставание. Срока здесь нет, беды
--- от раннего такта тоже, и вторых часов в настройках ради этого нет.
---
--- Такт бывает и внеочередным: `wake` будит паузу, и следующий такт
--- начинается сразу. Событие, о котором цикл узнаёт толчком — сосед
--- перестал принимать запись, узел сменил режим, — иначе ждало бы конца
--- периода, и время реакции равнялось бы периоду опроса. Толчок во время
--- такта не теряется: такт мог снять состояние до события, и следующий
--- идёт за ним без паузы. Толчки не копятся — сколько бы их ни пришло,
--- внеочередной такт один: он и так снимает всё, что случилось.
---
--- Каждый такт идёт в своей области контекста (`tnt-context`) с новым
--- опознавателем `request_id` — ULID из `tnt-id`. Без неё записи одного
--- такта обхода или смены лидера нечем связать между собой, а у
--- происшествия в такте нет номера, по которому искать его в журнале.
--- Область заводит цикл, а не владелец: такт зовёт цикл, и владелец,
--- забывший обернуть такт сам, оставил бы свои записи без опознавателя
--- молча — такое видно только по записям без поля. Отказ такта
--- (`on_error`) пишется в той же области: запись о падении несёт номер
--- упавшего такта. Операцию мельче такта — узел обхода, пачку — владелец
--- заводит вложенной областью `context.run` сам: её ключ ляжет поверх
--- тактового.
---
--- Контекст того, кто запустил цикл, не наследуется: фибер порождается
--- без `context.bind`. Цикл, лениво заведённый первым запросом, иначе нёс
--- бы его `request_id` во всех тактах до перезапуска узла. Между тактами
--- области нет.
---
--- `tnt-clock` пакет не берёт: ради одного вызова `fiber.clock` зависимость
--- не заводится. Часы вынесены в настройки, чтобы тесты обходились без
--- ожидания.

local fiber = require('fiber')

local context = require('tnt.context')
local id = require('tnt.id')
local must = require('tnt.must')

---@class TntLoop
---@field name string Имя фибера
---@field tick fun() Что делать на каждом такте
---@field interval number Период такта
---@field scheduler_now fun(): number Время планировщика
---@field on_error (fun(err: string))|nil Что делать с упавшим тактом
---@field on_stop (fun())|nil Что сделать при остановке
---@field fiber table|nil Фибер цикла
---@field condition table|nil Условная переменная остановки
---@field stopped boolean Остановлен ли цикл
---@field woken boolean Просили ли внеочередной такт
---@field generation table|nil Метка запуска: фибер прежнего запуска уходит
local Module = {}
Module.__index = Module

--- Период такта, если не задан иной.
local DEFAULT_INTERVAL = 5

---@class TntLoopOptions
---@field name string Имя фибера
---@field tick fun() Что делать на каждом такте
---@field interval number|nil Период такта
---@field scheduler_now (fun(): number)|nil Время планировщика
---@field on_error (fun(err: string))|nil Что делать с упавшим тактом
---@field on_stop (fun())|nil Что сделать при остановке

--- Описание настроек `new` для `must.options`.
---
--- Таблицей, а не проверкой на каждое поле: незнакомый ключ — тоже отказ.
--- Обработчик с опечаткой в имени иначе просто не применился бы, и падения
--- тактов уходили бы в пустоту.
local OPTIONS = {
    name = 'not_empty',
    tick = 'callable',
    interval = '?positive',
    scheduler_now = '?callable',
    on_error = '?callable',
    on_stop = '?callable',
}

--- Значение либо умолчание, если значения нет.
---
--- Нет значения — это и `nil`, и `box.NULL`: так приходит `null` из YAML
--- и JSON, и проверка необязательного его пропускает. `box.NULL` — cdata,
--- а cdata в Lua истинна, и `value or default` оставил бы его на месте:
--- арифметика паузы бросила бы в фибере, вне защиты такта.
---@param value any
---@param default any
---@return any
local function given_or(value, default)
    if value == nil then
        return default
    end

    return value
end

--- Время планировщика, если часы не подставлены.
---@return number
local function scheduler_clock()
    return fiber.clock()
end

--- Собирает цикл. Пока не запущен, ничего не делает.
---
--- Неправильные настройки — бросок на строке вызывающего: `name` —
--- непустая строка, `tick` — функция или вызываемая таблица, `interval` —
--- число больше нуля, обработчики и часы — функции; других ключей нет.
---@param opts TntLoopOptions
---@return TntLoop
function Module.new(opts)
    must.at(2).options(opts, 'настройки цикла', OPTIONS)

    return setmetatable({
        name = opts.name,
        tick = opts.tick,
        interval = given_or(opts.interval, DEFAULT_INTERVAL),
        scheduler_now = given_or(opts.scheduler_now, scheduler_clock),
        on_error = opts.on_error,
        on_stop = opts.on_stop,
        fiber = nil,
        condition = nil,
        stopped = true,
        woken = false,
        generation = nil,
    }, Module)
end

--- Меняет период такта на ходу.
---
--- Настройки приходят из конфигурации кластера и меняются вместе с ней,
--- а цикл к этому времени уже собран. Пустое значение — `nil` или
--- `box.NULL` — возвращает умолчание.
---
--- Не число — бросок на строке вызывающего: арифметика паузы идёт вне
--- защиты такта, и строка или таблица в периоде убили бы фибер молча.
--- Ноль и меньше, в отличие от `new`, годятся: период ставят и на ходу,
--- из самого такта, и там он значит «следующий такт — сразу».
---@param interval number|nil
function Module:set_interval(interval)
    must.at(2).optional.number(interval, 'период такта')

    self.interval = given_or(interval, DEFAULT_INTERVAL)
end

--- Сколько осталось ждать до следующего такта.
---
--- Не меньше нуля: такт, проработавший дольше периода, начинает следующий
--- сразу. Отсечено через `math.max`, а не развилкой: остаток, равный нулю,
--- и отрицательный означают одно — ждать нечего, — и граница развилки
--- (`<` или `<=`) не меняла бы ничего, то есть не была бы ничем проверена.
---@param started number Начало такта по времени планировщика
---@return number
function Module:pause_after(started)
    return math.max(0, self.interval - (self.scheduler_now() - started))
end

--- Ждёт указанное время либо до остановки или толчка, что наступит раньше.
---
--- Остановка будит ожидание сразу: иначе выключение наблюдения
--- задерживалось бы на целый период. Толчок, пришедший во время такта,
--- отменяет паузу после него: ждать нечего, состояние уже изменилось.
---@param seconds number
---@return boolean waited
function Module:wait_for(seconds)
    if self.stopped or self.woken or seconds <= 0 then
        return false
    end

    -- Условная переменная заводится вместе с циклом: до его запуска
    -- ожидание уже отсечено проверкой остановки выше. Возвращается сам
    -- факт ожидания, а не то, чем оно кончилось: разбудила остановка или
    -- вышел срок — для вызывающего одно и то же.
    assert(self.condition):wait(seconds)

    return true
end

--- Один такт под защитой: упавший отдаётся `on_error`.
---
--- Зовётся внутри области такта, поэтому запись о падении несёт тот же
--- `request_id`, что и записи самого такта.
---
--- Обработчик — тоже код владельца, и зовётся он под своим `pcall`:
--- брошенное из него убило бы фибер, такты прекратились бы молча,
--- а `running()` отвечал бы «да» — ровно то, от чего защищён такт.
--- Бросок обработчика глушится: сообщать о падениях и было его делом,
--- и сказать о его собственном больше некому.
---@param self TntLoop
local function guarded_tick(self)
    local ok, err = pcall(self.tick)

    if not ok and self.on_error ~= nil then
        pcall(self.on_error, tostring(err))
    end
end

--- Запускает цикл. Повторный запуск ничего не меняет.
---
--- Фибер помнит метку своего запуска: остановка и запуск без уступки
--- между ними — перечитывание конфигурации гасит прежний цикл и тут же
--- поднимает новый — иначе оставляли бы прежний фибер жить: проснувшись,
--- он видел бы цикл снова идущим и продолжал бы такты рядом с новым.
--- Метка — свежая таблица, а не счётчик: сравнивается только на равенство.
function Module:start()
    if not self.stopped then
        return
    end

    self.stopped = false
    self.condition = fiber.cond()
    self.generation = {}

    local generation = self.generation

    self.fiber = fiber.create(function()
        fiber.self():name(self.name, { truncate = true })

        while not self.stopped and self.generation == generation do
            local started = self.scheduler_now()

            -- Толчок, полученный до начала такта, этим тактом и исполнен.
            -- Сбрасывается до такта, а не после: толчок во время такта
            -- обязан пережить его и отменить паузу.
            self.woken = false

            -- Опознаватель — новый на каждый такт: такт и есть одна
            -- операция цикла, и записи соседних тактов не должны сливаться.
            context.run({ [context.REQUEST_ID] = id.ulid() }, guarded_tick, self)

            self:wait_for(self:pause_after(started))
        end
    end)
end

--- Просит такт вне очереди. Остановленный цикл не будит.
---
--- Пауза прерывается, а толчок во время такта запоминается и отменяет
--- паузу после него. Повторные толчки до такта складываются в один.
function Module:wake()
    if self.stopped then
        return
    end

    self.woken = true
    assert(self.condition):broadcast()
end

--- Останавливает цикл. Остановленный не трогает.
function Module:stop()
    if self.stopped then
        return
    end

    self.stopped = true
    assert(self.condition):broadcast()

    if self.on_stop ~= nil then
        self.on_stop()
    end
end

--- Идёт ли цикл прямо сейчас.
---@return boolean
function Module:running()
    return not self.stopped
end

return Module
